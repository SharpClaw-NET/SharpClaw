using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace SharpClaw.Build.GeneratedCodeSuppressions;

/// <summary>Preserves the pinned OpenAPI generator's exact XML-comment output.</summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class GeneratedCodeDiagnosticSuppressor : DiagnosticSuppressor
{
    private const string OpenApiOutputSuffix =
        "/Microsoft.AspNetCore.OpenApi.SourceGenerators/"
        + "Microsoft.AspNetCore.OpenApi.SourceGenerators.XmlCommentGenerator/"
        + "OpenApiXmlCommentSupport.generated.cs";

    private static readonly SuppressionDescriptor UniqueOpenApiMetadata = new(
        "SCG0001",
        "HLQ005",
        "Microsoft.AspNetCore.OpenApi 10.0.9 owns this exact XML-comment output. "
        + "Its SingleOrDefault lookups enforce unique metadata; FirstOrDefault weakens that contract.");

    private static readonly SuppressionDescriptor OpenApiParameterIteration = new(
        "SCG0002",
        "HLQ012",
        "Microsoft.AspNetCore.OpenApi 10.0.9 owns this exact XML-comment output. "
        + "Its emitted parameter-comment list iteration remains controlled by the pinned generator.");

    private static readonly ImmutableArray<SuppressionDescriptor> Suppressions =
        [UniqueOpenApiMetadata, OpenApiParameterIteration];

    public override ImmutableArray<SuppressionDescriptor> SupportedSuppressions => Suppressions;

    public override void ReportSuppressions(SuppressionAnalysisContext context)
    {
        var assemblyName = context.Compilation.AssemblyName;
        if (!string.Equals(assemblyName, "SharpClaw.Gateway", StringComparison.Ordinal)
            && !string.Equals(assemblyName, "SharpClaw.Tests", StringComparison.Ordinal))
            return;

        foreach (var diagnostic in context.ReportedDiagnostics)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            var suppression = GetSuppression(diagnostic.Id);
            if (suppression is null || diagnostic.Location.SourceTree is not { } tree)
                continue;

            // Roslyn appends the generator assembly, full type name and hint name
            // to its output directory. Normalize separators without weakening
            // the complete generator/output suffix or its ordinal comparison.
            var path = tree.FilePath.Replace('\\', '/');
            if (!path.EndsWith(OpenApiOutputSuffix, StringComparison.Ordinal)
                || !HasGeneratedHeader(tree, context.CancellationToken))
                continue;

            context.ReportSuppression(Suppression.Create(suppression, diagnostic));
        }
    }

    private static SuppressionDescriptor? GetSuppression(string diagnosticId)
    {
        if (string.Equals(diagnosticId, "HLQ005", StringComparison.Ordinal))
            return UniqueOpenApiMetadata;

        return string.Equals(diagnosticId, "HLQ012", StringComparison.Ordinal)
            ? OpenApiParameterIteration
            : null;
    }

    private static bool HasGeneratedHeader(SyntaxTree tree, CancellationToken cancellationToken)
    {
        foreach (var trivia in tree.GetRoot(cancellationToken).GetLeadingTrivia())
        {
            if (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia)
                && trivia.ToString().Contains("<auto-generated", StringComparison.Ordinal))
                return true;
        }

        return false;
    }
}
